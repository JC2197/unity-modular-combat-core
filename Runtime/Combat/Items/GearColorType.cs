/// <summary>
/// Shared color identity that pairs crafting orbs with the gear modifiers they produce.
/// A Red-type orb biases a tool toward producing Red-type gear modifiers, etc.
/// Used by both <see cref="OrbItemConfig"/> and <see cref="GearModifier"/>.
/// </summary>
public enum GearColorType
{
    Cyan,
    Magenta,
    Yellow,
    Red,
    Green,
    Black,
    Orange
}
